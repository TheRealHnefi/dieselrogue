use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let manifest_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let icon = format!("{}/dieselrogue.ico", manifest_dir);
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=dieselrogue.ico");

    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows")
        && Path::new(&icon).exists()
    {
        let mut res = winres::WindowsResource::new();
        res.set_icon(&icon);
        res.compile().expect("failed to compile Windows resources");
    }

    embed_blocks(&manifest_dir);
}

/// Bakes the map block files into the executable. Generates a Rust source file
/// in OUT_DIR listing every resources/blocks/*.txt as (filename, bytes); the
/// game includes it and never reads the directory at runtime.
fn embed_blocks(manifest_dir: &str) {
    println!("cargo:rerun-if-changed=resources/blocks");
    let blocks_dir = Path::new(manifest_dir).join("resources").join("blocks");

    let mut filenames: Vec<String> = fs::read_dir(&blocks_dir)
        .unwrap_or_else(|e| panic!("failed to read {}: {}", blocks_dir.display(), e))
        .map(|entry| {
            entry
                .unwrap_or_else(|e| panic!("failed to read {}: {}", blocks_dir.display(), e))
                .file_name()
                .into_string()
                .expect("block filename must be valid UTF-8")
        })
        .filter(|filename| filename.ends_with(".txt"))
        .collect();
    filenames.sort();

    assert!(
        !filenames.is_empty(),
        "no .txt block files found in resources/blocks"
    );

    let mut source = String::new();
    source.push_str("// Generated by build.rs — do not edit.\n");
    source.push_str("pub static BLOCK_FILES: &[(&str, &[u8])] = &[\n");
    for filename in &filenames {
        source.push_str(&format!(
            "  (\"{}\", include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/resources/blocks/{}\"))),\n",
            filename, filename
        ));
    }
    source.push_str("];\n");

    let out_dir = env::var("OUT_DIR").unwrap();
    fs::write(Path::new(&out_dir).join("blocks_data.rs"), source)
        .expect("failed to write blocks_data.rs");
}
